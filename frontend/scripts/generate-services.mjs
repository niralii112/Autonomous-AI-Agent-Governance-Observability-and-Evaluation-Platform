import fs from "node:fs";

const endpoints = JSON.parse(
  fs.readFileSync("api-endpoint-map.json", "utf8")
);

const operations = endpoints.flatMap(({ path, methods }) =>
  methods.map(({ method, operationId }) => ({
    path,
    method: method.toUpperCase(),
    operationId,
  }))
);

if (operations.length !== 55) {
  throw new Error(
    `Expected 55 operations, found ${operations.length}`
  );
}

const supportedMethods = new Set([
  "GET",
  "POST",
  "PUT",
  "PATCH",
  "DELETE",
]);

const names = new Set();

const lines = [
  'import { typedApi } from "./functions";',
  'import type { FetchOptions } from "openapi-fetch";',
  'import type { paths } from "../types/generated/api";',
  "",
  "/**",
  " * Generated from the shared OpenAPI endpoint map.",
  " * Do not edit this file manually.",
  " */",
  "",
];

for (const { path, method, operationId } of operations) {
  if (!supportedMethods.has(method)) {
    throw new Error(`Unsupported HTTP method: ${method}`);
  }

  if (!/^[A-Za-z_$][A-Za-z0-9_$]*$/.test(operationId)) {
    throw new Error(`Invalid operation ID: ${operationId}`);
  }

  if (names.has(operationId)) {
    throw new Error(`Duplicate operation ID: ${operationId}`);
  }

  names.add(operationId);

  const pathLiteral = JSON.stringify(path);
  const methodLiteral = method.toLowerCase();

  const operationType =
    `paths[${pathLiteral}][${JSON.stringify(methodLiteral)}]`;

  lines.push(
    `type ${operationId}Options = FetchOptions<${operationType}>;`,
    "",
    `export function ${operationId}(`,
    `  ...[options]: ${operationId}Options extends { body: unknown }`,
    `    ? [options: ${operationId}Options]`,
    `    : ${operationId}Options extends { params: unknown }`,
    `      ? [options: ${operationId}Options]`,
    `      : [options?: ${operationId}Options]`,
    `) {`,
    `  return typedApi.${method}(`,
    `    ${pathLiteral},`,
    `    options as ${operationId}Options`,
    `  );`,
    `}`,
    ""
  );
}

fs.writeFileSync(
  "src/api/generated-services.ts",
  lines.join("\n")
);

console.log(
  `Generated ${operations.length} endpoint-specific API functions.`
);
